#!/usr/bin/env python3
"""Exercise firstboot network generation without touching host networking."""
from pathlib import Path
import os
import shlex
import subprocess
import tempfile
import unittest


HOOK = Path(__file__).resolve().parents[1] / "firstboot.d" / "01ipconfig"


class IPConfigTest(unittest.TestCase):
    def run_hook(self, mode, initial):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            interfaces = root / "interfaces"
            interfaces.write_text(initial)
            (root / "hostname").write_text("appliance\n")
            (root / "defaults").write_text(
                "INITHOOKS_CONF=" + shlex.quote(str(root / "preseed")) + "\n")
            (root / "preseed").write_text(
                "IP_CONFIG=" + shlex.quote(mode) + "\n"
                "IP_ADDRESS=192.0.2.10\nIP_NETMASK=255.255.255.0\n"
                "IP_GW=192.0.2.1\nIP_DNS1=192.0.2.53\nIP_DNS2=192.0.2.54\n")
            source = HOOK.read_text()
            for original, fixture in (
                ("/etc/default/inithooks", "defaults"),
                ("/etc/network/interfaces", "interfaces"),
                ("/etc/hostname", "hostname"),
            ):
                source = source.replace(original, str(root / fixture))
            (root / "hook").write_text(source)
            for command in ("ip", "ifup", "turnkey-version"):
                stub = root / command
                stub.write_text(
                    "#!/bin/sh\n" + (
                        "echo core\n" if command == "turnkey-version" else
                        'printf "%s\\n" "' + command + ' $*" >> "$CALL_LOG"\n'))
                stub.chmod(0o755)
            env = dict(os.environ, PATH=str(root) + ":/usr/bin:/bin",
                       CALL_LOG=str(root / "calls"))
            result = subprocess.run(["bash", "-e", str(root / "hook")],
                                    env=env, capture_output=True, text=True)
            calls = root / "calls"
            return result, interfaces.read_text(), calls.read_text() if calls.exists() else ""

    def test_static_keeps_interface_stanzas_and_appends_address(self):
        result, config, calls = self.run_hook("static", "iface eth0 inet dhcp\n")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(config, """# interfaces(5) file - generated by TurnKey firstboot

auto lo
iface lo inet loopback

auto eth0
iface eth0 inet static
    hostname appliance
    address 192.0.2.10
    netmask 255.255.255.0
    gateway 192.0.2.1
    dns-nameservers 192.0.2.53 192.0.2.54
""")
        self.assertEqual(calls, "ip link set eth0 down\nifup --all --exclude=lo\n")

    def test_dhcp_transition_retains_complete_stanzas(self):
        result, config, calls = self.run_hook("dhcp", "iface eth0 inet manual\n")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("auto lo\niface lo inet loopback\n", config)
        self.assertIn("auto eth0\niface eth0 inet dhcp\n    hostname appliance\n", config)
        self.assertNotIn("address ", config)
        self.assertEqual(calls, "ip link set eth0 down\nifup --all --exclude=lo\n")

    def test_existing_dhcp_configuration_is_untouched(self):
        initial = "auto eth0\niface eth0 inet dhcp\n    mtu 1400\n"
        result, config, calls = self.run_hook("dhcp", initial)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(config, initial)
        self.assertEqual(calls, "")

    def test_invalid_mode_does_not_reconfigure_network(self):
        initial = "iface eth0 inet dhcp\n"
        result, config, calls = self.run_hook("invalid", initial)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("Invalid: IP_CONFIG", result.stderr)
        self.assertEqual(config, initial)
        self.assertEqual(calls, "")


if __name__ == "__main__":
    unittest.main()
